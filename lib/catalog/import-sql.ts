// The import as one SQL transaction, for running in a SQL session against
// STAGING when no service-role key is at hand (scripts/import-rosters.ts
// --emit-sql). Same rows the --upsert path writes: programs upserted by
// slug, each program's class counts replaced wholesale. Pure.
//
// It carries what ProgramDraft carries and nothing more: no player name,
// no hometown, no Notes cell. Head coach is stored by design (printed on
// the official roster page), as in the --upsert path.
//
// Guard: it raises before writing anything unless migration 048's tables
// exist, which is true on staging and NOT on production (048 is unapplied
// there). That is a seatbelt, not the control — the control is that this
// file is only ever run against staging.

import type { ProgramDraft } from "./roster-import";

function lit(v: string | number | null): string {
  if (v === null) return "null";
  if (typeof v === "number") {
    if (!Number.isFinite(v)) throw new Error(`not a finite number: ${v}`);
    return String(v);
  }
  return `'${v.replace(/'/g, "''")}'`;
}

export function buildImportSql(drafts: readonly ProgramDraft[], checkedOn: string): string {
  if (!/^\d{4}-\d{2}-\d{2}$/.test(checkedOn)) throw new Error(`checkedOn must be yyyy-mm-dd, got ${checkedOn}`);
  const out: string[] = [
    "-- Generated by scripts/import-rosters.ts --emit-sql. STAGING ONLY.",
    "begin;",
    "do $$ begin",
    "  if to_regclass('public.programs') is null or to_regclass('public.program_class_counts') is null then",
    "    raise exception 'migration 048 is not on this database: refusing (this file is for staging)';",
    "  end if;",
    "end $$;",
  ];
  if (drafts.length === 0) throw new Error("no programs to import");
  const date = `${lit(checkedOn)}::date`;
  // 1. Programs, set-based: one upsert for all of them.
  out.push(
    "insert into public.programs (slug, school, gender, division, conference, head_coach, roster_url, " +
      "season_shown, season_start_year, players_listed, unknown_class_count, last_verified, source_url, source_date)\n" +
      "select v.slug, v.school, v.gender, v.division, v.conference, v.head_coach, v.roster_url, v.season_shown, " +
      `v.season_start_year, v.players_listed, v.unknown_class_count, ${date}, v.roster_url, ${date} from (values\n` +
      drafts
        .map(
          (d) =>
            "(" +
            [
              lit(d.slug),
              lit(d.school),
              lit(d.gender),
              lit(d.division),
              lit(d.conference),
              lit(d.headCoach) + "::text",
              lit(d.rosterUrl) + "::text",
              lit(d.seasonShown),
              lit(d.seasonStartYear),
              lit(d.playersListed),
              lit(d.unknownClassCount),
            ].join(",") +
            ")"
        )
        .join(",\n") +
      "\n) as v(slug, school, gender, division, conference, head_coach, roster_url, season_shown, " +
      "season_start_year, players_listed, unknown_class_count)\n" +
      "on conflict (slug) do update set school = excluded.school, gender = excluded.gender, " +
      "division = excluded.division, conference = excluded.conference, head_coach = excluded.head_coach, " +
      "roster_url = excluded.roster_url, season_shown = excluded.season_shown, " +
      "season_start_year = excluded.season_start_year, players_listed = excluded.players_listed, " +
      "unknown_class_count = excluded.unknown_class_count, last_verified = excluded.last_verified, " +
      "source_url = excluded.source_url, source_date = excluded.source_date;"
  );
  // 2. Each imported program's counts are a snapshot: replace them wholesale.
  out.push(
    "delete from public.program_class_counts c using public.programs p where c.program_id = p.id and p.slug in (" +
      drafts.map((d) => lit(d.slug)).join(",") +
      ");"
  );
  const counts = drafts.flatMap((d) =>
    Object.entries(d.classCounts).map(([y, n]) => `(${lit(d.slug)},${lit(Number(y))},${lit(n)})`)
  );
  if (counts.length) {
    out.push(
      "insert into public.program_class_counts (program_id, class_year, players)\n" +
        "select p.id, v.y, v.n from (values\n" +
        counts.join(",\n") +
        "\n) as v(slug, y, n) join public.programs p on p.slug = v.slug;"
    );
  }
  out.push("commit;");
  return out.join("\n") + "\n";
}
