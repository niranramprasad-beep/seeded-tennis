import { describe, expect, it } from "vitest";
import { readFileSync, readdirSync, statSync } from "node:fs";
import { join } from "node:path";

// Guards the fix in migration 036 + lib/db/family-scope.ts.
//
// THE BUG THIS EXISTS TO PREVENT COMING BACK
// "Which family does this user belong to?" has two storage shapes: the
// creator's `profiles.family_code`, and every joiner's `parent_accounts` row
// (whose profiles.family_code is deliberately NULL, because writing that
// column is the family-takeover hole 022/032 closed).
//
// Eight call sites across five files scoped their queries by reading
// `profiles.family_code` directly. For a parent who joined with the code that
// is NULL, so each one bailed out — `if (!p.family_code) return []` — BEFORE
// RLS was ever consulted. The visible symptom was /family showing a parent
// none of their own player's real numbers. The invisible one was that a
// joined parent could not write the season budget or an encouragement note
// at all, which is the entire list of things a parent is allowed to write.
//
// `my_family_code()` (migration 026) answers across both shapes. Ask it.

const ROOTS = ["lib", "app", "components"];

/** lib/auth.ts is the one legitimate reader of the raw column, and the
 * reason is load-bearing rather than stylistic: mapProfileToPlayer() round-
 * trips the value straight back through writeCurrentPlayerProfile(), and
 * 022/030/035's trigger rejects ANY client change to family_code with 42501.
 * Substituting a joiner's real code there would make renaming yourself in
 * Settings fail for every member who joined with a code. */
const ALLOWED = new Set([
  "lib/auth.ts",
  // Generated by `generate_typescript_types`. It declares no behaviour and
  // runs no query; it trips the detector only on the foreign-key metadata
  // (`columns: ["family_code"]`). Regenerating it must not fail the build.
  "lib/db/database.types.ts",
]);

/** Removes comments while LEAVING string literals intact.
 *
 * Both of those properties are load-bearing, and each was a real bug:
 *  - A naive stripper that deletes from any `//` to end of line eats the
 *    rest of a line containing a URL, so `const u = "https://x//y"; if
 *    (p.family_code) …` was never seen. An independent review defeated the
 *    first version of this detector that way.
 *  - A stripper that blanks strings to avoid that then breaks the
 *    cross-user-profiles check below, which has to see `from("profiles")`.
 * So this walks the source and tracks what it is inside. */
export function stripComments(source: string): string {
  let out = "";
  let i = 0;
  const n = source.length;
  while (i < n) {
    const c = source[i];
    const next = source[i + 1];
    if (c === "/" && next === "/") {
      while (i < n && source[i] !== "\n") i++;
      continue;
    }
    if (c === "/" && next === "*") {
      i += 2;
      while (i < n && !(source[i] === "*" && source[i + 1] === "/")) i++;
      i += 2;
      continue;
    }
    if (c === '"' || c === "'" || c === "`") {
      const quote = c;
      out += c;
      i++;
      while (i < n) {
        if (source[i] === "\\") {
          out += source[i] + (source[i + 1] ?? "");
          i += 2;
          continue;
        }
        out += source[i];
        if (source[i] === quote) {
          i++;
          break;
        }
        i++;
      }
      continue;
    }
    out += c;
    i++;
  }
  return out;
}

/** The offence: reading a profile row's `family_code` to scope by family.
 *
 * Matches ANY receiver, not a hard-coded list of four names — the first
 * version missed `prof?.family_code`, `row.family_code`,
 * `myProfile.family_code`, `p["family_code"]` and
 * `const { family_code } = await profile()`. All five are caught now. */
const OFFENDING: RegExp[] = [
  /\.\s*family_code\b/,
  /\[\s*["'`]family_code["'`]\s*\]/,
  /\{[^{}]*\bfamily_code\b[^{}]*\}\s*=/,
];

export function offends(source: string): boolean {
  const clean = stripComments(source);
  return OFFENDING.some((re) => re.test(clean));
}

/** The second invariant, from migration 037: no cross-user `profiles` read.
 *
 * RLS cannot narrow COLUMNS, so any policy letting one member read another
 * member's `profiles` row exposes the whole row — gpa, birth_year,
 * whop_membership_id, both stripe ids. 037 dropped `family_members_read`
 * and moved the roster into `family_members()`, whose column list is
 * enumerated. A `.from("profiles")` filtered by anything other than the
 * caller's own id would reopen it. */
export function readsOtherProfiles(source: string): boolean {
  const clean = stripComments(source);
  if (!/\.\s*from\(\s*["'`]profiles["'`]/.test(clean)) return false;
  return /\.\s*in\(\s*["'`]id["'`]/.test(clean) || /\.\s*neq\(\s*["'`]id["'`]/.test(clean);
}

function walk(dir: string, out: string[] = []): string[] {
  for (const entry of readdirSync(dir)) {
    if (entry === "node_modules" || entry === ".next") continue;
    const full = join(dir, entry);
    if (statSync(full).isDirectory()) walk(full, out);
    else if (/\.tsx?$/.test(entry) && !/\.test\.tsx?$/.test(entry)) out.push(full);
  }
  return out;
}

describe("the detector itself is not vacuous", () => {
  // Three vacuous guards shipped in one night (a `\s` in a POSIX-ERE
  // `git grep -E` pattern matches nothing; an anchor on git grep's own
  // `file:line:` output prefix never matches file content). Then an
  // independent review defeated the FIRST version of this detector eight
  // ways. Every one of those eight is a case below, so the guard cannot
  // quietly weaken back to where it was.
  it("flags the shapes that were actually wrong", () => {
    expect(offends('query.eq("family_code", p.family_code)')).toBe(true);
    expect(offends("if (!supabase || !p?.family_code) return [];")).toBe(true);
    expect(offends("familyCode: data?.family_code ?? null,")).toBe(true);
    expect(offends("family_code: profile.family_code ?? undefined,")).toBe(true);
  });

  it("flags the eight the review used to defeat the first version", () => {
    expect(offends("const { family_code } = await profile();")).toBe(true);
    expect(offends("if (!prof?.family_code) return [];")).toBe(true);
    expect(offends('query.eq("family_code", row.family_code)')).toBe(true);
    expect(offends('query.eq("family_code", myProfile.family_code)')).toBe(true);
    expect(offends('query.eq("family_code", profileRow.family_code)')).toBe(true);
    expect(offends('query.eq("family_code", p["family_code"])')).toBe(true);
    // The one that mattered most: a `//` inside a string literal used to
    // make the comment-stripper swallow the rest of the line.
    expect(offends('const u = "https://x//y"; if (p.family_code) doIt();')).toBe(true);
    expect(offends("const { family_code, role } = profileData;")).toBe(true);
  });

  it("does not flag prose that merely mentions the column", () => {
    expect(offends("// never scope by p.family_code — ask my_family_code()")).toBe(false);
    expect(offends("/* p?.family_code is NULL for a joiner */")).toBe(false);
  });

  it("does not flag the correct shapes", () => {
    expect(offends('query.eq("family_code", familyCode)')).toBe(false);
    expect(offends("const familyCode = await resolveMyFamilyCode(supabase);")).toBe(false);
    expect(offends("family_code: ctx.familyCode,")).toBe(false);
    expect(offends('insert({ family_code: familyCode, parent_id: id })')).toBe(false);
  });

  it("flags a cross-user profiles read, and not an own-row one", () => {
    expect(readsOtherProfiles('supabase.from("profiles").select("id,name").in("id", ids)')).toBe(true);
    expect(readsOtherProfiles('supabase.from("profiles").select("*").eq("id", id)')).toBe(false);
    expect(readsOtherProfiles('supabase.from("matches").select("*").in("id", ids)')).toBe(false);
  });
});

describe("no file scopes a family query by profiles.family_code", () => {
  const files = ROOTS.flatMap((r) => walk(r));

  it("finds a real, non-trivial set of files to check", () => {
    // If the walk breaks, every assertion below passes for the wrong reason.
    expect(files.length).toBeGreaterThan(200);
    expect(files).toContain(join("lib", "db", "family.ts"));
    expect(files).toContain(join("lib", "db", "events.ts"));
    expect(files).toContain(join("lib", "api-auth.ts"));
  });

  it("has no offenders outside the one documented exception", () => {
    const offenders = files
      .filter((f) => !ALLOWED.has(f.split(/[\\/]/).join("/")))
      .filter((f) => offends(readFileSync(f, "utf8")));
    expect(offenders).toEqual([]);
  });

  it("no file reads another user's profiles row", () => {
    // The invariant migration 037 establishes. lib/auth.ts and the API routes
    // read the CALLER's own row, which readsOtherProfiles() does not flag.
    const offenders = files.filter((f) => readsOtherProfiles(readFileSync(f, "utf8")));
    expect(offenders).toEqual([]);
  });

  it("still finds the documented exception, so the allow-list is real", () => {
    // If lib/auth.ts ever stops reading the raw column, delete it from
    // ALLOWED in the same commit rather than leaving a stale exemption.
    expect(offends(readFileSync(join("lib", "auth.ts"), "utf8"))).toBe(true);
  });
});

describe("migration 036 keeps the parts the fix depends on", () => {
  const sql = readFileSync(
    join("supabase", "migrations", "036_family_membership_both_shapes.sql"),
    "utf8"
  );

  it("defines the one membership predicate and keeps EXECUTE for authenticated", () => {
    expect(sql).toContain("create or replace function public.shares_approved_family_with");
    // Revoking this fails every policy that calls it CLOSED — proven on
    // staging in 027. Do not re-litigate it from the advisor's wording.
    expect(sql).toMatch(
      /grant execute on function public\.shares_approved_family_with\(uuid\) to authenticated/
    );
  });

  it("only counts APPROVED links, so a pending member is not a member", () => {
    expect(sql).toMatch(/status = 'approved'/);
    expect(sql).not.toMatch(/status\s*(?:=|in)\s*\(?'pending'/);
  });

  it("rewrites every family read policy that keyed off the owner's profile column", () => {
    for (const policy of [
      "family_members_read",
      "utr_entries_select_family",
      "matches_read",
      "tournament_entries_read",
      "coach_outreach_read",
      "daily_checkins_read",
      "cost_calculations_read",
    ]) {
      expect(sql).toContain(`create policy "${policy}"`);
    }
  });

  it("stamps family_code in the database and freezes it on UPDATE", () => {
    expect(sql).toContain("create or replace function public.stamp_family_code");
    // INSERT takes the server's answer, never the client's.
    expect(sql).toContain("new.family_code := public.my_family_code();");
    // UPDATE cannot re-parent a row into another family.
    expect(sql).toContain("new.family_code := old.family_code;");
    for (const table of [
      "matches",
      "coach_outreach",
      "tournament_entries",
      "daily_checkins",
      "cost_calculations",
      "encouragement_notes",
      "season_budgets",
      "budget_expenses",
      "parent_reports",
    ]) {
      expect(sql).toContain(`'${table}'`);
    }
  });

  it("does NOT set a joiner's profiles.family_code", () => {
    // That write is the takeover capability, and remove_family_member() only
    // deletes the parent_accounts row — so a removed member would keep a
    // family_code and keep their access. Revocation lives in one place.
    expect(sql).not.toMatch(/update\s+public\.profiles\s+set\s+family_code/i);
  });
});

describe("migration 037 keeps the parts that make /privacy true", () => {
  const sql = readFileSync(
    join("supabase", "migrations", "037_revoke_on_removal_and_narrow_family_reads.sql"),
    "utf8"
  );

  it("removal clears the removed member's profile family_code", () => {
    // Without this, "the moment a member is removed they can no longer see
    // anything about anyone in it" is false for every member production has:
    // all three of its parent_accounts rows also carry the code on their own
    // profile, and both my_family_code() and shares_approved_family_with()
    // fall back to that column.
    expect(sql).toMatch(/update public\.profiles set family_code = null/);
  });

  it("refuses to remove the family's account holder", () => {
    // 026 said the account holder is not evictable; it was true only by
    // accident. Clearing their code on someone else's say-so locked them out
    // of their own family — reproduced on staging before this shipped.
    expect(sql).toContain("create or replace function public.family_account_holder");
    expect(sql).toMatch(
      /if p_user_id = public\.family_account_holder\(v_code\) then\s*\n\s*raise exception/
    );
  });

  it("only clears the code when somebody else still holds it", () => {
    expect(sql).toMatch(/if v_other_holders > 0 then/);
  });

  it("drops the cross-user profiles policy and enumerates the roster columns", () => {
    expect(sql).toMatch(/drop policy if exists "family_members_read" on public\.profiles/);
    // A return type cannot change under CREATE OR REPLACE (42P13), and a
    // fresh CREATE after a DROP re-grants EXECUTE to PUBLIC.
    expect(sql).toMatch(/drop function if exists public\.family_members\(\)/);
    expect(sql).toMatch(/grant execute on function public\.family_members\(\) to authenticated/);
    for (const col of ["current_utr", "grade", "graduation_year", "onboarded",
                       "target_school_slugs", "gender"]) {
      expect(sql).toContain(col);
    }
    // The columns that must NOT be in the cross-user surface.
    for (const col of ["gpa", "birth_year", "whop_membership_id",
                       "stripe_customer_id", "stripe_subscription_id"]) {
      expect(sql.includes(`  ${col} `)).toBe(false);
    }
  });
});

