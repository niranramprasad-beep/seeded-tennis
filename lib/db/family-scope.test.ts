// Guards the fix in migration 036 + lib/db/family-scope.ts.
//
// THE BUG THIS EXISTS TO PREVENT COMING BACK
// "Which family does this user belong to?" has two storage shapes: the
// creator's `profiles.family_code`, and every joiner's `parent_accounts` row
// (whose profiles.family_code is deliberately NULL, because writing that
// column is the family-takeover hole 022/032 closed).
//
// Eight call sites across five files scoped their queries by reading
// `profiles.family_code` directly. For a parent who joined with the code that
// is NULL, so each one bailed out — `if (!p.family_code) return []` — BEFORE
// RLS was ever consulted. The visible symptom was /family showing a parent
// none of their own player's real numbers. The invisible one was that a
// joined parent could not write the season budget or an encouragement note
// at all, which is the entire list of things a parent is allowed to write.
//
// `my_family_code()` (migration 026) answers across both shapes. Ask it.

const ROOTS = ["lib", "app", "components"];

/** lib/auth.ts is the one legitimate reader of the raw column, and the
 * reason is load-bearing rather than stylistic: mapProfileToPlayer() round-
 * trips the value straight back through writeCurrentPlayerProfile(), and
 * 022/030/035's trigger rejects ANY client change to family_code with 42501.
 * Substituting a joiner's real code there would make renaming yourself in
 * Settings fail for every member who joined with a code. */
const ALLOWED = new Set([
  "lib/auth.ts",
  // The ONE deliberate cross-user `profiles` read in the codebase, and it is
  // not a family read. `findUserIdByEmail()` looks an account up by email so
  // the Whop webhook can attach a purchase to it — the buyer's Whop email is
  // all the webhook has. It runs on the server with the service role (which
  // bypasses RLS, so no policy is involved), selects `id` only, and refuses
  // unless exactly one row matches (`.limit(2)` then `length !== 1`). If that
  // ever reads more than `id`, or runs with anything but the service role,
  // delete this entry instead of widening it.
  "lib/whop-sync.ts",
  // Generated by `generate_typescript_types`. It declares no behaviour and
  // runs no query; it trips the detector only on the foreign-key metadata
  // (`columns: ["family_code"]`). Regenerating it must not fail the build.
  "lib/db/database.types.ts",
]);

/** Removes comments while LEAVING string literals intact.
 *
 * Both of those properties are load-bearing, and each was a real bug:
 *  - A naive stripper that deletes from any `//` to end of line eats the
 *    rest of a line containing a URL, so `const u = "https://x//y"; if
 *    (p.family_code) …` was never seen. An independent review defeated the
 *    first version of this detector that way.
 *  - A stripper that blanks strings to avoid that then breaks the
 *    cross-user-profiles check below, which has to see `from("profiles")`.
 * So this walks the source and tracks what it is inside. */
export function stripComments(source: string): string {
  let out = "";
  let i = 0;
  const n = source.length;
  while (i < n) {
    const c = source[i];
    const next = source[i + 1];
    if (c === "/" && next === "/") {
      while (i < n && source[i] !== "\n") i++;
      continue;
    }
    if (c === "/" && next === "*") {
      i += 2;
      while (i < n && !(source[i] === "*" && source[i + 1] === "/")) i++;
      i += 2;
      continue;
    }
    if (c === '"' || c === "'" || c === "`") {
      const quote = c;
      out += c;
      i++;
      while (i < n) {
        if (source[i] === "\\") {
          out += source[i] + (source[i + 1] ?? "");
          i += 2;
          continue;
        }
        out += source[i];
        if (source[i] === quote) {
          i++;
          break;
        }
        i++;
      }
      continue;
    }
    out += c;
    i++;
  }
  return out;
}

/** The offence: reading a profile row's `family_code` to scope by family.
 *
 * Matches ANY receiver, not a hard-coded list of four names — the first
 * version missed `prof?.family_code`, `row.family_code`,
 * `myProfile.family_code`, `p["family_code"]` and
 * `const { family_code } = await profile()`. All five are caught now. */
const OFFENDING: RegExp[] = [
  /\.\s*family_code\b/,
  /\[\s*["'`]family_code["'`]\s*\]/,
  /\{[^{}]*\bfamily_code\b[^{}]*\}\s*=/,
];

/** A bracket index built by concatenating literals — `row["family" + "_code"]`
 *  — which the regexes above cannot see because neither literal is the whole
 *  column name. An independent review used exactly this to read the raw
 *  column past the guard. Only folds expressions made ENTIRELY of string
 *  literals, `+` and whitespace, so a genuine dynamic key is left alone. */
function foldsToFamilyCode(source: string): boolean {
  for (const m of source.matchAll(/\[([^[\]]*)\]/g)) {
    const inner = m[1];
    if (!/^[\s+]*(["'`][^"'`]*["'`][\s+]*)+$/.test(inner)) continue;
    const joined = [...inner.matchAll(/["'`]([^"'`]*)["'`]/g)].map((x) => x[1]).join("");
    if (joined === "family_code") return true;
  }
  return false;
}

export function offends(source: string): boolean {
  const clean = stripComments(source);
  return OFFENDING.some((re) => re.test(clean)) || foldsToFamilyCode(clean);
}

/** The second invariant, from migration 037: no cross-user `profiles` read.
 *
 * RLS cannot narrow COLUMNS, so any policy letting one member read another
 * member's `profiles` row exposes the whole row — gpa, birth_year,
 * whop_membership_id, both stripe ids. 037 dropped `family_members_read` and
 * moved the roster into `family_members()`, whose column list is enumerated.
 *
 * THIS FUNCTION WAS REWRITTEN AFTER AN INDEPENDENT REVIEW DEFEATED IT.
 * The first version asked only "does this file contain `.in("id"` or
 * `.neq("id"`?". A reviewer added one scratch file and got the whole build
 * green — 646 tests passing — while doing all of this:
 *
 *     .from("profiles").select("id,name,email,gpa,birth_year,…")
 *                      .eq("family_code", familyCode)   // the 037 pattern
 *     .from("profiles").select("*").or(`id.in.(${ids})`)
 *     .from("profiles").select("*").filter("id", "in", `(${ids})`)
 *
 * Six bypasses in all, each a case in the suite below. CLAUDE.md claimed this
 * guard "fails the build on either reintroduction"; for this invariant it did
 * not. So the rule is now shaped so that the decidable thing is the thing
 * checked:
 *
 *   **Every `profiles` chain must be a single-row read by id.** It must
 *   contain `.eq("id", …)`, and it must not contain a multi-row or
 *   escape-hatch filter (`.in`, `.or`, `.filter`, `.neq`, `.not`, `.match`,
 *   `.contains`, `.like`, `.ilike`, a range) — least of all
 *   `.eq("family_code", …)`.
 *
 * What this deliberately does NOT catch, said plainly rather than implied:
 * `.eq("id", someoneElsesId)`. That is one row, and RLS returns zero for it
 * (`profiles_select_own` is the only SELECT policy left after 037), so the
 * database is the control there, not this lint. This is a lint, not a proof. */
const PROFILE_CHAIN_BANNED: { re: RegExp; why: string }[] = [
  { re: /\.\s*eq\(\s*["'`]family_code["'`]/, why: 'scoped by profiles.family_code' },
  { re: /\.\s*in\(/, why: '.in() — a multi-row read' },
  { re: /\.\s*or\(/, why: '.or() — a multi-row read' },
  { re: /\.\s*filter\(/, why: '.filter() — the untyped escape hatch' },
  { re: /\.\s*neq\(/, why: '.neq()' },
  { re: /\.\s*not\(/, why: '.not()' },
  { re: /\.\s*match\(/, why: '.match()' },
  { re: /\.\s*contains\(/, why: '.contains()' },
  { re: /\.\s*i?like\(/, why: 'a LIKE/ILIKE search across rows' },
  { re: /\.\s*(gte?|lte?)\(/, why: 'a range filter' },
];

/** Each `.from("profiles")` chain in the source, as text: from the `.from`
 *  to the end of that statement. */
export function profilesChains(source: string): string[] {
  const clean = stripComments(source);
  const chains: string[] = [];
  // The table name may be a CONST, not a literal. A verifier defeated
  // this detector with
  //   const PROFILES_TABLE = "profiles";
  //   supabase.from(PROFILES_TABLE).select(...).in("id", ids)
  // which reads every listed row and matched nothing, because the regex
  // keyed on the literal. Any identifier whose name mentions "profile" is
  // now treated as the profiles table too — indirection is not an escape.
  // Match the ARGUMENT, then decide — rather than trying to guess every
  // identifier spelling. The first attempt at this used
  // `[Pp]rofiles?(_?[Tt]able)?` and missed `PROFILES_TABLE`, which is
  // precisely the constant the verifier used.
  const re = /\.\s*from\(\s*([^)]{1,60}?)\s*\)/g;
  let m: RegExpExecArray | null;
  while ((m = re.exec(clean)) !== null) {
    if (!/profile/i.test(m[1])) continue;
    const window = clean.slice(m.index, m.index + 900);
    const end = window.indexOf(";");
    let chain = end === -1 ? window : window.slice(0, end);
    // A query assigned to a variable and filtered in a LATER statement —
    //   let q = supabase.from("profiles").select("*");
    //   q = q.in("id", ids);
    // — stopped at the first `;` and read as one harmless chain
    // (verifier, 2026-11-16). Every later `q.<filter>(` in the file is
    // appended to the chain it belongs to.
    const assigned = clean.slice(Math.max(0, m.index - 120), m.index).match(/(?:const|let|var)\s+(\w+)\s*=\s*[\w!.?\s]*$/)?.[1];
    if (assigned) {
      const later = new RegExp(String.raw`\b${assigned}\s*(?:=\s*${assigned}\s*)?((?:\.\s*\w+\([^;]*)+)`, "g");
      const rest = clean.slice(m.index + chain.length);
      for (const l of rest.matchAll(later)) chain += l[1];
    }
    chains.push(chain);
  }
  return chains;
}

/** The profiles table named anywhere but a direct `.from(...)` (or a
 *  generated row type): a helper like `table(supabase, "profiles")` hides
 *  the whole chain from the lint above (verifier, 2026-11-16). */
export function profilesNameOutsideFrom(source: string): boolean {
  const clean = stripComments(source);
  for (const m of clean.matchAll(/["'`]profiles["'`]/g)) {
    const before = clean.slice(Math.max(0, m.index! - 30), m.index!);
    if (/\.\s*from\(\s*$/.test(before)) continue;
    if (/\b(?:Tables|TablesInsert|TablesUpdate)<\s*$/.test(before)) continue;
    return true;
  }
  return false;
}

/** Why this source reads another user's profiles row, or [] if it does not. */
export function profileReadProblems(source: string): string[] {
  const problems: string[] = [];
  for (const chain of profilesChains(source)) {
    for (const { re, why } of PROFILE_CHAIN_BANNED) {
      if (re.test(chain)) problems.push(why);
    }
    if (!/\.\s*eq\(\s*["'`]id["'`]/.test(chain)) {
      problems.push('not scoped by .eq("id", …) — it can match more than the caller\'s own row');
    }
  }
  return [...new Set(problems)];
}

export function readsOtherProfiles(source: string): boolean {
  return profileReadProblems(source).length > 0 || profilesNameOutsideFrom(source);
}

function walk(dir: string, out: string[] = []): string[] {
  for (const entry of readdirSync(dir)) {
    if (entry === "node_modules" || entry === ".next") continue;
    const full = join(dir, entry);
    if (statSync(full).isDirectory()) walk(full, out);
    else if (/\.tsx?$/.test(entry) && !/\.test\.tsx?$/.test(entry)) out.push(full);
  }
  return out;
}

describe("the detector itself is not vacuous", () => {
  // Three vacuous guards shipped in one night (a `\s` in a POSIX-ERE
  // `git grep -E` pattern matches nothing; an anchor on git grep's own
  // `file:line:` output prefix never matches file content). Then an
  // independent review defeated the FIRST version of this detector eight
  // ways. Every one of those eight is a case below, so the guard cannot
  // quietly weaken back to where it was.
  it("flags the shapes that were actually wrong", () => {
    expect(offends('query.eq("family_code", p.family_code)')).toBe(true);
    expect(offends("if (!supabase || !p?.family_code) return [];")).toBe(true);
    expect(offends("familyCode: data?.family_code ?? null,")).toBe(true);
    expect(offends("family_code: profile.family_code ?? undefined,")).toBe(true);
  });

  it("flags the eight the review used to defeat the first version", () => {
    expect(offends("const { family_code } = await profile();")).toBe(true);
    expect(offends("if (!prof?.family_code) return [];")).toBe(true);
    expect(offends('query.eq("family_code", row.family_code)')).toBe(true);
    expect(offends('query.eq("family_code", myProfile.family_code)')).toBe(true);
    expect(offends('query.eq("family_code", profileRow.family_code)')).toBe(true);
    expect(offends('query.eq("family_code", p["family_code"])')).toBe(true);
    // The one that mattered most: a `//` inside a string literal used to
    // make the comment-stripper swallow the rest of the line.
    expect(offends('const u = "https://x//y"; if (p.family_code) doIt();')).toBe(true);
    expect(offends("const { family_code, role } = profileData;")).toBe(true);
  });

  it("does not flag prose that merely mentions the column", () => {
    expect(offends("// never scope by p.family_code — ask my_family_code()")).toBe(false);
    expect(offends("/* p?.family_code is NULL for a joiner */")).toBe(false);
  });

  it("does not flag the correct shapes", () => {
    expect(offends('query.eq("family_code", familyCode)')).toBe(false);
    expect(offends("const familyCode = await resolveMyFamilyCode(supabase);")).toBe(false);
    expect(offends("family_code: ctx.familyCode,")).toBe(false);
    expect(offends('insert({ family_code: familyCode, parent_id: id })')).toBe(false);
  });

  it("flags a cross-user profiles read, and not an own-row one", () => {
    expect(readsOtherProfiles('supabase.from("profiles").select("id,name").in("id", ids)')).toBe(true);
    expect(readsOtherProfiles('supabase.from("profiles").select("*").eq("id", id)')).toBe(false);
    expect(readsOtherProfiles('supabase.from("matches").select("*").in("id", ids)')).toBe(false);
    // Indirection through a constant must not help.
    expect(
      readsOtherProfiles('supabase.from(PROFILES_TABLE).select("id,name,gpa").in("id", ids)'),
      "a const table name is still the profiles table"
    ).toBe(true);
    expect(
      readsOtherProfiles('supabase.from(profilesTable).select("*").eq("family_code", code)')
    ).toBe(true);
  });

  it("flags the two a 2026-11-16 review used to defeat the current version", () => {
    expect(
      readsOtherProfiles('const table = (s: any, n: string) => s.from(n);\nawait table(supabase, "profiles").select("*").in("id", ids);')
    ).toBe(true);
    expect(
      readsOtherProfiles('let q = supabase.from("profiles").select("*");\nq = q.in("id", ids);\nawait q;')
    ).toBe(true);
    // ...and still not the own-row read with a follow-up on another variable.
    expect(
      readsOtherProfiles('const { data } = await supabase.from("profiles").select("name").eq("id", user.id).maybeSingle();\nconst x = rows.in;')
    ).toBe(false);
  });

  it("flags the six an independent review used to defeat the first version", () => {
    // Every one of these passed the previous detector with the whole build
    // green. The first is the exact pattern migration 037 exists to prevent.
    expect(
      readsOtherProfiles(
        'await supabase.from("profiles").select("id,name,email,gpa,birth_year,whop_membership_id").eq("family_code", familyCode);'
      )
    ).toBe(true);
    expect(readsOtherProfiles('await supabase.from("profiles").select("*").or(`id.in.(${ids})`);')).toBe(true);
    expect(readsOtherProfiles('await supabase.from("profiles").select("*").filter("id", "in", `(${ids})`);')).toBe(true);
    expect(readsOtherProfiles('await supabase.from("profiles").select("family_code").eq("id", me);')).toBe(false);
    expect(readsOtherProfiles('await supabase.from("profiles").select("*");')).toBe(true);
    expect(readsOtherProfiles('await supabase.from("profiles").select("id").ilike("email", pattern).limit(2);')).toBe(true);
    // the computed-key read of the raw column, which `offends()` missed
    expect(offends('const code = (row as Record<string, string | null>)["family" + "_code"];')).toBe(true);
  });

  it("says WHY a profiles read is a problem, so the failure is actionable", () => {
    expect(
      profileReadProblems('supabase.from("profiles").select("*").eq("family_code", code).eq("id", me)')
    ).toContain("scoped by profiles.family_code");
    expect(profileReadProblems('supabase.from("profiles").select("*")')).toHaveLength(1);
    expect(profileReadProblems('supabase.from("profiles").select("*").eq("id", me)')).toEqual([]);
  });

  it("reads each profiles chain separately, so one safe chain cannot cover a bad one", () => {
    const mixed = [
      'const a = await supabase.from("profiles").select("*").eq("id", me).maybeSingle();',
      'const b = await supabase.from("profiles").select("*").eq("family_code", code);',
    ].join("\n");
    expect(profilesChains(mixed)).toHaveLength(2);
    expect(readsOtherProfiles(mixed)).toBe(true);
  });
});

describe("no file scopes a family query by profiles.family_code", () => {
  const files = ROOTS.flatMap((r) => walk(r));

  it("finds a real, non-trivial set of files to check", () => {
    // If the walk breaks, every assertion below passes for the wrong reason.
    expect(files.length).toBeGreaterThan(200);
    expect(files).toContain(join("lib", "db", "family.ts"));
    expect(files).toContain(join("lib", "db", "events.ts"));
    expect(files).toContain(join("lib", "api-auth.ts"));
  });

  it("has no offenders outside the one documented exception", () => {
    const offenders = files
      .filter((f) => !ALLOWED.has(f.split(/[\\/]/).join("/")))
      .filter((f) => offends(readFileSync(f, "utf8")));
    expect(offenders).toEqual([]);
  });

  it("no file reads another user's profiles row", () => {
    // The invariant migration 037 establishes. Every legitimate site reads
    // the CALLER's own row by id; the one deliberate cross-user lookup
    // (lib/whop-sync.ts, service role, email -> id) is on the allow-list with
    // its reason.
    const offenders = files
      .filter((f) => !ALLOWED.has(f.split(/[\\/]/).join("/")))
      .map((f) => ({ f, why: profileReadProblems(readFileSync(f, "utf8")) }))
      .filter((x) => x.why.length > 0)
      .map((x) => `${x.f}: ${x.why.join("; ")}`);
    expect(offenders).toEqual([]);
  });

  it("still flags the allow-listed cross-user read, so that exemption is real", () => {
    // If lib/whop-sync.ts stops reading profiles across users, delete it from
    // ALLOWED in the same commit rather than leaving a stale exemption.
    expect(readsOtherProfiles(readFileSync(join("lib", "whop-sync.ts"), "utf8"))).toBe(true);
  });

  it("still finds the documented exception, so the allow-list is real", () => {
    // If lib/auth.ts ever stops reading the raw column, delete it from
    // ALLOWED in the same commit rather than leaving a stale exemption.
    expect(offends(readFileSync(join("lib", "auth.ts"), "utf8"))).toBe(true);
  });
});

